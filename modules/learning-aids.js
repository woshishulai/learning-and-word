export function cleanPreferences(value = {}) {
	return {
		mode: ["context", "homophone", "listening"].includes(value.mode)
			? value.mode
			: "context",
		english:
			typeof value.english === "boolean"
				? value.english
				: value.mode !== "listening",
		images: value.images !== false,
		ipa: value.ipa !== false,
		meaning: value.meaning !== false,
		examples: value.examples !== false,
		notes: value.notes !== false,
		homophones: value.homophones === true,
		translation: value.translation === true,
		accent: value.accent === "en-GB" ? "en-GB" : "en-US",
		rate: [0.65, 0.85, 1].includes(Number(value.rate))
			? Number(value.rate)
			: 0.85,
	};
}
